// Writes ASSETS.md from public/assets/manifest.json plus the things built in code.
import { readFile, writeFile } from "node:fs/promises";

const manifest = JSON.parse(await readFile("public/assets/manifest.json", "utf8"));
const mb = (n) => (n / 1048576).toFixed(1);

const rows = (type) =>
  manifest
    .filter((m) => m.type === type)
    .map((m) => `| \`${m.id}\` | ${m.name} | [${m.url.replace("https://", "")}](${m.url}) | ${m.licence} | ${m.authors.join(", ") || "n/a"} | ${m.polycount ?? ""} | ${mb(m.bytes)} MB (${m.resolution}) | ${m.fetched} |`)
    .join("\n");

const head = "| id | Name | Source | Licence | Author | Triangles (source) | Size | Fetched |\n|---|---|---|---|---|---|---|---|";

const md = `# Assets and licences

Generated by \`node scripts/write-assets-md.mjs\` from \`public/assets/manifest.json\`. Poly Haven assets are CC0: no credit needed, any use allowed (https://polyhaven.com/license). Credit is given anyway.

## Downloaded models (used in the game)

${head}
${rows("models")}

## Downloaded textures (PBR, used on equipment, ground and walls)

${head}
${rows("textures")}

## Downloaded sky

${head}
${rows("hdris")}

## Built in code (no licence to track)

| id | What | Notes |
|---|---|---|
| \`pump_skid\` | High-pressure pump on a steel skid | Shapes plus Poly Haven textures above |
| \`membrane_rack\` | Rack of six membrane vessels | Same |
| \`tank\` | Product-water tank | Same |
| \`terminal\` | Control post with screen and stack light | Same |
| \`sea_tile\` | Animated sea surface | Waves in code |
| \`operator\` | **Placeholder** person with white hard hat and teal vest | To be replaced by a licensed realistic character |
| ambient sound | Sea, wind, machinery and birds made in the browser | Synthesised, nothing downloaded |

## Library

| Package | Use | Licence |
|---|---|---|
| three 0.187.0 | 3D engine | MIT |
| @dgreenheck/ez-tree 1.1.0 | Procedural trees and shrubs | MIT |

## Looked at and not used

- OpenGameArt "High Quality Industrial Asset Pack" (CC0): ships only Blender files and 100 MB of textures, and Blender is not installed. Removed.
- Quaternius: its own licence (QAL v1.0) forbids redistributing the assets as assets. Not used.
- Kenney: CC0, but the packs are stylised, not realistic. Not used.
- Sketchfab, Mixamo, Poly Pizza: need an account or an API key. Not used.
`;
await writeFile("ASSETS.md", md);
console.log("ASSETS.md written");
